"use client"

import { useState, useEffect, use } from "react"
import { useAuth } from "@/components/providers/auth-provider"
import { useRouter } from "next/navigation"
import { db } from "@/lib/firebase"
import { doc, getDoc } from "firebase/firestore"
import { Button } from "@/components/ui/button"
import {
    ArrowLeft, Download, FileText, Loader2,
    CheckCircle2, List, Zap, BookOpen, FileDown, RotateCcw, Trophy
} from "lucide-react"
import { toast } from "sonner"

const OUTPUT_TYPES = [
    { value: "Bullet points",    label: "Bullet Points" },
    { value: "Detailed notes",   label: "Detailed Notes" },
    { value: "Short notes",      label: "Short Notes" },
    { value: "Exam prep",        label: "Exam Prep" },
    { value: "Quiz",             label: "Quiz" },
    { value: "Assignment guide", label: "Assignment Guide" },
    { value: "Paragraph",        label: "Paragraph" },
]

export default function SummaryResultPage({ params }: { params: Promise<{ summaryId: string }> }) {
    const { summaryId } = use(params)
    const { user }      = useAuth()
    const router        = useRouter()

    const [summary, setSummary]     = useState<any>(null)
    const [loading, setLoading]     = useState(true)
    const [exporting, setExporting] = useState<"pdf" | "word" | null>(null)
    // Quiz state: maps question index → chosen letter (A/B/C/D)
    const [userAnswers, setUserAnswers] = useState<Record<number, string>>({})

    useEffect(() => {
        if (!user || !summaryId) return
        getDoc(doc(db, "users", user.uid, "summaries", summaryId))
            .then(snap => {
                if (snap.exists()) setSummary({ id: snap.id, ...snap.data() })
                else toast.error("Summary not found.")
            })
            .catch(() => toast.error("Failed to load summary."))
            .finally(() => setLoading(false))
    }, [user, summaryId])

    // ── Export as PDF (browser print) ────────────────────────────────────────
    const exportPDF = () => {
        setExporting("pdf")
        // Small delay so the state update hides export buttons before print dialog opens
        setTimeout(() => {
            window.print()
            setExporting(null)
        }, 150)
    }

    // ── Export as Word (.doc via HTML blob) ──────────────────────────────────
    const exportWord = () => {
        if (!summary) return
        setExporting("word")

        const kpHtml = summary.keyPoints?.length
            ? `<h2 style="color:#1a56db;font-size:14pt;margin:20pt 0 6pt">Key Points</h2>
               <ul style="margin:0;padding-left:18pt">${summary.keyPoints.map((p: string) =>
                   `<li style="margin-bottom:5pt;font-size:11pt">${escapeHtml(p)}</li>`
               ).join("")}</ul>`
            : ""

        const aiHtml = summary.actionItems?.length
            ? `<h2 style="color:#c05621;font-size:14pt;margin:20pt 0 6pt">Action Plan</h2>
               <ul style="margin:0;padding-left:18pt">${summary.actionItems.map((a: string) =>
                   `<li style="margin-bottom:5pt;font-size:11pt">${escapeHtml(a)}</li>`
               ).join("")}</ul>`
            : ""

        const metaLine = [summary.outputType, summary.tone, summary.length].filter(Boolean).join(" · ")

        const html = `
<!DOCTYPE html>
<html>
<head>
  <meta charset="utf-8">
  <style>
    body { font-family: Calibri, Arial, sans-serif; font-size: 11pt; line-height: 1.6; margin: 2cm; color: #1a1a1a; }
    h1   { font-size: 20pt; margin: 0 0 4pt; }
    .meta { font-size: 9pt; color: #888; margin-bottom: 18pt; }
    h2   { font-size: 13pt; margin: 18pt 0 6pt; }
    p    { margin: 0 0 12pt; }
    .overview-box { background: #f5f5f5; padding: 12pt; border-left: 4pt solid #1a56db; margin-bottom: 18pt; }
    .footer { margin-top: 30pt; font-size: 8pt; color: #aaa; border-top: 1pt solid #ddd; padding-top: 6pt; }
  </style>
</head>
<body>
  <h1>${escapeHtml(summary.emoji || "")} ${escapeHtml(summary.title || "Summary")}</h1>
  ${metaLine ? `<div class="meta">${escapeHtml(metaLine)}</div>` : ""}

  <h2 style="color:#1a56db;font-size:14pt;margin:0 0 6pt">Overview</h2>
  <div class="overview-box"><p>${escapeHtml(summary.summary || "")}</p></div>

  ${kpHtml}
  ${aiHtml}

  <div class="footer">Generated by AI Note Summarizer · ${new Date().toLocaleDateString()}</div>
</body>
</html>`

        const blob = new Blob([html], { type: "application/msword" })
        const url  = URL.createObjectURL(blob)
        const a    = document.createElement("a")
        a.href     = url
        a.download = `${(summary.title || "summary").replace(/[^a-z0-9]/gi, "_")}.doc`
        a.click()
        URL.revokeObjectURL(url)

        toast.success("Downloaded as Word document!")
        setExporting(null)
    }

    if (loading) return (
        <div className="flex h-64 items-center justify-center">
            <Loader2 className="h-8 w-8 animate-spin text-primary" />
        </div>
    )

    if (!summary) return (
        <div className="flex flex-col items-center justify-center h-64 gap-4">
            <FileText className="h-12 w-12 text-muted-foreground/30" />
            <p className="text-muted-foreground">Summary not found.</p>
            <Button variant="outline" onClick={() => router.push("/dashboard/note-summarizer")}>
                ← Back
            </Button>
        </div>
    )

    const metaBadge = [summary.outputType, summary.tone, summary.length].filter(Boolean)

    return (
        <>
            {/* Print styles — hides everything except the summary content */}
            <style jsx global>{`
                @media print {
                    .no-print { display: none !important; }
                    body      { background: white !important; }
                    @page     { margin: 1.5cm; }
                }
            `}</style>

            <div className="container max-w-3xl py-8">
                {/* Top bar */}
                <div className="flex items-center justify-between mb-8 no-print">
                    <Button
                        variant="ghost"
                        size="sm"
                        onClick={() => router.push("/dashboard/note-summarizer")}
                        className="gap-2 pl-0"
                    >
                        <ArrowLeft className="h-4 w-4" /> Back
                    </Button>

                    <div className="flex gap-2">
                        <Button
                            variant="outline"
                            size="sm"
                            onClick={exportWord}
                            disabled={!!exporting}
                            className="gap-2"
                        >
                            {exporting === "word"
                                ? <Loader2 className="h-4 w-4 animate-spin" />
                                : <FileDown className="h-4 w-4" />}
                            Download Word
                        </Button>
                        <Button
                            size="sm"
                            onClick={exportPDF}
                            disabled={!!exporting}
                            className="gap-2"
                        >
                            {exporting === "pdf"
                                ? <Loader2 className="h-4 w-4 animate-spin" />
                                : <Download className="h-4 w-4" />}
                            Download PDF
                        </Button>
                    </div>
                </div>

                {/* ── Summary content (printed as-is) ── */}
                <article className="space-y-7">
                    {/* Title */}
                    <div>
                        <h1 className="text-3xl font-bold leading-snug flex items-start gap-3">
                            <span className="text-4xl leading-none mt-0.5">{summary.emoji}</span>
                            <span>{summary.title}</span>
                        </h1>
                        {metaBadge.length > 0 && (
                            <div className="flex gap-2 mt-2 flex-wrap">
                                {metaBadge.map((b: string) => (
                                    <span key={b} className="text-xs px-2.5 py-0.5 rounded-full bg-muted text-muted-foreground font-medium">
                                        {b}
                                    </span>
                                ))}
                                {summary.fileName && (
                                    <span className="text-xs px-2.5 py-0.5 rounded-full bg-muted text-muted-foreground font-medium flex items-center gap-1">
                                        <FileText className="h-3 w-3" />
                                        {summary.fileName}
                                    </span>
                                )}
                            </div>
                        )}
                    </div>

                    {/* Overview */}
                    <section>
                        <h2 className="flex items-center gap-2 text-sm font-bold uppercase tracking-widest text-primary mb-3">
                            <BookOpen className="h-4 w-4" /> Overview
                        </h2>
                        <div className="bg-primary/5 border-l-4 border-primary rounded-r-lg p-5">
                            <p className="text-base leading-relaxed">{summary.summary}</p>
                        </div>
                    </section>

                    {/* ── MCQ Quiz (when outputType is Quiz) ── */}
                    {summary.outputType === "Quiz" && summary.questions?.length > 0 && (() => {
                        const questions: { q: string; options: string[]; answer: string; explanation: string }[] = summary.questions
                        const answered    = Object.keys(userAnswers).length
                        const correct     = questions.filter((q, i) => userAnswers[i] === q.answer).length
                        const allAnswered = answered === questions.length

                        return (
                            <section>
                                {/* Score bar */}
                                {allAnswered && (
                                    <div className={`flex items-center gap-4 p-4 rounded-xl mb-6 border ${
                                        correct === questions.length
                                            ? "bg-green-50 dark:bg-green-950/30 border-green-200 dark:border-green-800"
                                            : correct >= questions.length * 0.7
                                            ? "bg-blue-50 dark:bg-blue-950/30 border-blue-200 dark:border-blue-800"
                                            : "bg-amber-50 dark:bg-amber-950/20 border-amber-200 dark:border-amber-800"
                                    }`}>
                                        <Trophy className={`h-8 w-8 shrink-0 ${
                                            correct === questions.length ? "text-green-500" :
                                            correct >= questions.length * 0.7 ? "text-blue-500" : "text-amber-500"
                                        }`} />
                                        <div className="flex-1">
                                            <p className="font-bold text-lg">{correct}/{questions.length} correct</p>
                                            <p className="text-sm text-muted-foreground">
                                                {correct === questions.length ? "Perfect score!" :
                                                 correct >= questions.length * 0.7 ? "Great job! Review the ones you missed." :
                                                 "Keep studying — retake the quiz to improve your score."}
                                            </p>
                                        </div>
                                        <button
                                            onClick={() => setUserAnswers({})}
                                            className="flex items-center gap-1.5 text-sm text-muted-foreground hover:text-foreground transition-colors"
                                        >
                                            <RotateCcw className="h-4 w-4" /> Retake
                                        </button>
                                    </div>
                                )}

                                {/* Questions */}
                                <div className="space-y-6">
                                    {questions.map((q, qi) => {
                                        const chosen    = userAnswers[qi]
                                        const isCorrect = chosen === q.answer

                                        return (
                                            <div key={qi} className={`rounded-xl border p-5 transition-all ${
                                                chosen
                                                    ? isCorrect
                                                        ? "border-green-300 dark:border-green-700 bg-green-50/50 dark:bg-green-950/20"
                                                        : "border-red-300 dark:border-red-700 bg-red-50/50 dark:bg-red-950/20"
                                                    : "border-border"
                                            }`}>
                                                {/* Question */}
                                                <p className="font-semibold text-base mb-4 leading-snug">
                                                    <span className="text-primary mr-2">Q{qi + 1}.</span>
                                                    {q.q}
                                                </p>

                                                {/* Options */}
                                                <div className="grid grid-cols-1 sm:grid-cols-2 gap-2 mb-3">
                                                    {q.options.map((opt, oi) => {
                                                        const letter = ["A","B","C","D"][oi]
                                                        const isChosen  = chosen === letter
                                                        const isAnswer  = q.answer === letter
                                                        const revealed  = !!chosen

                                                        let btnClass = "flex items-start gap-2.5 w-full px-4 py-2.5 rounded-lg border text-sm text-left transition-all "

                                                        if (revealed) {
                                                            if (isAnswer) {
                                                                btnClass += "bg-green-500 border-green-500 text-white font-semibold"
                                                            } else if (isChosen) {
                                                                btnClass += "bg-red-500 border-red-500 text-white"
                                                            } else {
                                                                btnClass += "border-border text-muted-foreground opacity-50"
                                                            }
                                                        } else {
                                                            btnClass += "border-border hover:border-primary hover:bg-primary/5 cursor-pointer"
                                                        }

                                                        return (
                                                            <button
                                                                key={oi}
                                                                disabled={!!chosen}
                                                                onClick={() => setUserAnswers(prev => ({ ...prev, [qi]: letter }))}
                                                                className={btnClass}
                                                            >
                                                                <span className={`font-bold shrink-0 mt-0.5 ${revealed && isAnswer ? "text-white" : revealed && isChosen ? "text-white" : "text-primary"}`}>
                                                                    {letter}.
                                                                </span>
                                                                <span>{opt.replace(/^[A-D]\.\s*/, "")}</span>
                                                            </button>
                                                        )
                                                    })}
                                                </div>

                                                {/* Explanation (shown after answering) */}
                                                {chosen && q.explanation && (
                                                    <div className={`flex gap-2 text-sm mt-3 p-3 rounded-lg ${
                                                        isCorrect
                                                            ? "bg-green-100 dark:bg-green-900/30 text-green-800 dark:text-green-300"
                                                            : "bg-blue-50 dark:bg-blue-900/30 text-blue-800 dark:text-blue-300"
                                                    }`}>
                                                        <CheckCircle2 className="h-4 w-4 shrink-0 mt-0.5" />
                                                        <span><strong>Correct answer: {q.answer}.</strong> {q.explanation}</span>
                                                    </div>
                                                )}
                                            </div>
                                        )
                                    })}
                                </div>
                            </section>
                        )
                    })()}

                    {/* Key Points (non-quiz output types) */}
                    {summary.outputType !== "Quiz" && summary.keyPoints?.length > 0 && (
                        <section>
                            <h2 className="flex items-center gap-2 text-sm font-bold uppercase tracking-widest text-blue-600 mb-3">
                                <List className="h-4 w-4" /> Key Points
                            </h2>
                            <ul className="space-y-3">
                                {summary.keyPoints.map((point: string, i: number) => (
                                    <li key={i} className="flex gap-3 text-base leading-relaxed">
                                        <CheckCircle2 className="h-5 w-5 text-green-500 shrink-0 mt-0.5" />
                                        <span>{point}</span>
                                    </li>
                                ))}
                            </ul>
                        </section>
                    )}

                    {/* Action Items */}
                    {summary.actionItems?.length > 0 && (
                        <section>
                            <h2 className="flex items-center gap-2 text-sm font-bold uppercase tracking-widest text-orange-600 mb-3">
                                <Zap className="h-4 w-4" /> Action Plan
                            </h2>
                            <ul className="space-y-2">
                                {summary.actionItems.map((item: string, i: number) => (
                                    <li key={i} className="flex gap-3 text-base leading-relaxed">
                                        <span className="text-orange-400 font-bold shrink-0">{i + 1}.</span>
                                        <span>{item}</span>
                                    </li>
                                ))}
                            </ul>
                        </section>
                    )}

                    {/* Print footer */}
                    <div className="hidden print:block mt-12 pt-4 border-t text-xs text-muted-foreground">
                        Generated by AI Note Summarizer · {new Date().toLocaleDateString()}
                        {summary.fileName ? ` · Source: ${summary.fileName}` : ""}
                    </div>
                </article>

                {/* Bottom export bar (duplicate for convenience) */}
                <div className="flex gap-3 mt-10 pt-6 border-t no-print">
                    <Button
                        variant="outline"
                        onClick={exportWord}
                        disabled={!!exporting}
                        className="gap-2 flex-1"
                    >
                        {exporting === "word" ? <Loader2 className="h-4 w-4 animate-spin" /> : <FileDown className="h-4 w-4" />}
                        Download as Word (.doc)
                    </Button>
                    <Button
                        onClick={exportPDF}
                        disabled={!!exporting}
                        className="gap-2 flex-1"
                    >
                        {exporting === "pdf" ? <Loader2 className="h-4 w-4 animate-spin" /> : <Download className="h-4 w-4" />}
                        Download as PDF
                    </Button>
                </div>
            </div>
        </>
    )
}

function escapeHtml(str: string): string {
    return str
        .replace(/&/g, "&amp;")
        .replace(/</g, "&lt;")
        .replace(/>/g, "&gt;")
        .replace(/"/g, "&quot;")
        .replace(/'/g, "&#039;")
}
